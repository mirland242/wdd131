/*

## What each section does

* **Logo/Header**: Identifies the business.
* **Navigation**: Links to the main pages.
* **Hero Banner**: First thing visitors see; includes a slogan and image.
* **About Us**: Brief introduction to the company.
* **Services**: What the business offers.
* **Testimonials**: Customer feedback and trust-building.
* **Contact Form**: Allows visitors to reach the business.
* **Footer**: Contact details, social media, copyright.

## Typography Example

For a professional small business site:

* **Montserrat** — Headings (`h1`, `h2`, `h3`)
* **Open Sans** — Body text and paragraphs

Both are available from [Google Fonts](https://fonts.google.com?utm_source=chatgpt.com) and are widely used because they're clean and readable.

## Color Schema Example

| Color     | Hex Code | Usage                        |
| --------- | -------- | ---------------------------- |
| Dark Blue | #1F3A5F  | Header, navigation, headings |
| Gold      | #D4A017  | Buttons, highlights, accents |
| White     | #FFFFFF  | Background and content areas |

This combination tends to give a small business website a professional and trustworthy appearance.

One thing to consider before finalizing your wireframe: what kind of business is it? For example, a photography business, architectural firm, consulting company, restaurant, or clothing brand would each benefit from slightly different sections and layouts.
*/

